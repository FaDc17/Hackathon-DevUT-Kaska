CREATE TABLE IF NOT EXISTS CategoriasServicio (
    IdCategoria INTEGER PRIMARY KEY AUTOINCREMENT,
    NombreCategoria TEXT NOT NULL COLLATE NOCASE,
    Descripcion TEXT,
    CONSTRAINT UQ_CategoriasServicio_Nombre UNIQUE (NombreCategoria)
);

CREATE TABLE IF NOT EXISTS TiposPublicacion (
    IdTipoPublicacion INTEGER PRIMARY KEY AUTOINCREMENT,
    NombreTipo TEXT NOT NULL COLLATE NOCASE,
    Descripcion TEXT,
    CONSTRAINT UQ_TiposPublicacion_Nombre UNIQUE (NombreTipo)
);

CREATE TABLE IF NOT EXISTS Usuarios (
    IdUsuario TEXT PRIMARY KEY,
    NombreUsuario TEXT NOT NULL COLLATE NOCASE,
    ContrasenaHash TEXT NOT NULL,
    Celular TEXT NOT NULL,
    DireccionPrivada TEXT NOT NULL,
    IdDistrito INTEGER NOT NULL,
    DescripcionPerfil TEXT,
    RemoteId TEXT,
    FechaRegistro TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
    FechaActualizacion TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
    Estado INTEGER NOT NULL DEFAULT 1 CHECK (Estado IN (0, 1)),
    SyncEstado TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (SyncEstado IN ('pendiente', 'sincronizado', 'error')),
    Eliminado INTEGER NOT NULL DEFAULT 0 CHECK (Eliminado IN (0, 1)),
    CONSTRAINT UQ_Usuarios_NombreUsuario UNIQUE (NombreUsuario),
    CONSTRAINT UQ_Usuarios_Celular UNIQUE (Celular),
    CONSTRAINT UQ_Usuarios_RemoteId UNIQUE (RemoteId),
    CONSTRAINT CK_Usuarios_Celular CHECK (length(Celular) = 9 AND Celular GLOB '[0-9]*' AND length(trim(Celular, '0123456789')) = 0),
    CONSTRAINT FK_Usuarios_Distritos
        FOREIGN KEY (IdDistrito) REFERENCES Distritos(IdDistrito)
        ON UPDATE CASCADE ON DELETE RESTRICT
