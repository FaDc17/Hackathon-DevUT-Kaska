CREATE TRIGGER IF NOT EXISTS TR_Publicaciones_CrearEmergencia
AFTER INSERT ON Publicaciones
WHEN EXISTS (
    SELECT 1 FROM TiposPublicacion
    WHERE IdTipoPublicacion = NEW.IdTipoPublicacion AND NombreTipo = 'Emergencia'
)
BEGIN
    INSERT INTO Emergencias(IdEmergencia, IdPublicacion)
    VALUES ('emergencia-' || NEW.IdPublicacion, NEW.IdPublicacion);
END;

CREATE TRIGGER IF NOT EXISTS TR_CanalesAyuda_VerificarDistrito
BEFORE INSERT ON CanalesAyuda
WHEN NEW.IdDistrito IS NOT NULL AND NEW.IdDepartamento IS NOT NULL
BEGIN
    SELECT CASE WHEN NOT EXISTS (
        SELECT 1 FROM Distritos
        WHERE IdDistrito = NEW.IdDistrito AND IdDepartamento = NEW.IdDepartamento
    ) THEN RAISE(ABORT, 'Distrito y departamento inconsistentes') END;
END;

CREATE TRIGGER IF NOT EXISTS TR_CanalesAyuda_VerificarDistrito_Update
BEFORE UPDATE OF IdDistrito, IdDepartamento ON CanalesAyuda
WHEN NEW.IdDistrito IS NOT NULL AND NEW.IdDepartamento IS NOT NULL
BEGIN
    SELECT CASE WHEN NOT EXISTS (
        SELECT 1 FROM Distritos
        WHERE IdDistrito = NEW.IdDistrito AND IdDepartamento = NEW.IdDepartamento
    ) THEN RAISE(ABORT, 'Distrito y departamento inconsistentes') END;
END;

