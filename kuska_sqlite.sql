CREATE TABLE IF NOT EXISTS Departamentos (
    IdDepartamento INTEGER PRIMARY KEY AUTOINCREMENT,
    NombreDepartamento TEXT NOT NULL COLLATE NOCASE,
    CONSTRAINT UQ_Departamentos_Nombre UNIQUE (NombreDepartamento)
);

CREATE TABLE IF NOT EXISTS Distritos (
    IdDistrito INTEGER PRIMARY KEY AUTOINCREMENT,
    IdDepartamento INTEGER NOT NULL,
    NombreProvincia TEXT NOT NULL,
    NombreDistrito TEXT NOT NULL,
    CONSTRAINT UQ_Distritos_Dep_Prov_Dist UNIQUE (IdDepartamento, NombreProvincia, NombreDistrito),
    CONSTRAINT FK_Distritos_Departamentos
        FOREIGN KEY (IdDepartamento) REFERENCES Departamentos(IdDepartamento)
        ON UPDATE CASCADE ON DELETE RESTRICT
