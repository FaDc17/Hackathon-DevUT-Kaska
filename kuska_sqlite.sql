CREATE TABLE IF NOT EXISTS Servicios (
    IdServicio TEXT PRIMARY KEY,
    IdUsuario TEXT NOT NULL,
    IdCategoria INTEGER NOT NULL,
    Titulo TEXT NOT NULL,
    Descripcion TEXT NOT NULL,
    PrecioMinimo REAL,
    PrecioMaximo REAL,
    UbicacionAproximada TEXT,
    Latitud REAL,
    Longitud REAL,
    RadioCoberturaMetros REAL,
    RemoteId TEXT,
    FechaPublicacion TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
    FechaActualizacion TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now')),
    Estado INTEGER NOT NULL DEFAULT 1 CHECK (Estado IN (0, 1)),
    SyncEstado TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (SyncEstado IN ('pendiente', 'sincronizado', 'error')),
    Eliminado INTEGER NOT NULL DEFAULT 0 CHECK (Eliminado IN (0, 1)),
    CONSTRAINT UQ_Servicios_RemoteId UNIQUE (RemoteId),
